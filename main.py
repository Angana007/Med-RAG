logger = logging.getLogger("clinical-rag")

# ── API Key Authentication ─────────────────────────────────────────────────────
# Reads the valid key from an environment variable — never hardcoded.
# Set it before starting the server:  export CLINICAL_RAG_API_KEY="your-secret"
# All clinical endpoints require this key in the X-API-Key header.
# /health is intentionally left open (monitoring tools don't need auth).

_API_KEY_NAME   = "X-API-Key"
_API_KEY_HEADER = APIKeyHeader(name=_API_KEY_NAME, auto_error=False)
_VALID_API_KEY  = os.environ.get("CLINICAL_RAG_API_KEY", "dev-key-change-in-prod")

# ── Safety Retry-Then-Block Policy ─────────────────────────────────────────────
# If a safety violation (PHI leak / cross-patient leak) is detected:
#   1. Regenerate ONCE with a stricter prompt (generate_answer_strict).
#   2. Re-run the safety check on the regenerated answer.
#   3. If still flagged → BLOCK the response entirely, return this generic message.
# Full violation details are always logged internally regardless of outcome.
BLOCKED_SAFETY_MESSAGE = (
    "This response could not be safely generated and has been withheld. "
    "Please rephrase your question or contact support if this persists."
)

async def require_api_key(api_key: str = Security(_API_KEY_HEADER)):
    """FastAPI dependency — inject into any endpoint to protect it."""
    if api_key != _VALID_API_KEY:
        logger.warning(f"Rejected request: invalid or missing API key.")
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail={"error": "Forbidden", "message": "Invalid or missing API key."}
        )
    return api_key


# ── Per-IP Rate Limiter ────────────────────────────────────────────────────────
# Limits each IP to RATE_LIMIT_MAX_REQUESTS per RATE_LIMIT_WINDOW_SECONDS.
# Prevents a single client from flooding Phi-3 (which runs on local CPU/GPU).
# For multi-worker deployments: replace with Redis-backed sliding window.

RATE_LIMIT_MAX_REQUESTS = 10    # max requests per window per IP
RATE_LIMIT_WINDOW_S     = 60    # window size in seconds

_rate_limit_store: Dict[str, Any] = defaultdict(lambda: {"count": 0, "window_start": 0.0})

async def check_rate_limit(request: Request):
    """FastAPI dependency — inject into any endpoint to enforce rate limiting."""
    client_ip   = request.client.host
    now         = time.time()
    record      = _rate_limit_store[client_ip]

    # Reset window if it has expired
    if now - record["window_start"] > RATE_LIMIT_WINDOW_S:
        record["count"]         = 0
        record["window_start"]  = now

    record["count"] += 1

    if record["count"] > RATE_LIMIT_MAX_REQUESTS:
        retry_after = int(RATE_LIMIT_WINDOW_S - (now - record["window_start"]))
        logger.warning(f"Rate limit exceeded for IP: {client_ip}")
        raise HTTPException(
            status_code=status.HTTP_429_TOO_MANY_REQUESTS,
            detail={
                "error":        "Rate_Limit_Exceeded",
                "message":      f"Too many requests. Limit: {RATE_LIMIT_MAX_REQUESTS} per {RATE_LIMIT_WINDOW_S}s.",
                "retry_after_s": retry_after,
            }
        )


