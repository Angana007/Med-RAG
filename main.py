"""
Module: main.py

The primary entry point for the Clinical RAG Assistant API — a FastAPI
app that orchestrates the full request flow: retrieval.py (SQL + vector
context) -> llm.py (Phi-3 answer generation) -> evaluation.py (live
safety/quality checks) -> structured JSON response.

Endpoints:
    POST /query    Submit a clinical question for a given MRD number.
                    Requires X-API-Key header. Rate-limited per IP.
    GET  /health   Multi-component health probe (LLM + retrieval).
    GET  /metrics  Runtime telemetry (query counts, latency, errors).
                    Requires X-API-Key header.
    GET  /docs     Interactive Swagger UI (auto-generated by FastAPI).

Run directly with `python main.py`, or via `uvicorn main:app --reload`
for auto-reload during development. Set CLINICAL_RAG_API_KEY in the
environment before starting — see "API Key Authentication" below.

Safety policy in one line: if a generated answer trips the PHI/cross-
patient safety check, main.py regenerates it ONCE with a stricter prompt;
if it's still unsafe, the response is blocked entirely (see the
"Retry-Then-Block Policy" section inside process_clinical_query below).
"""

